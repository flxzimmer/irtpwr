

#' Load IRT model functions and derivatives
#'
#' This is a helper function used to generate custom hypotheses. See the 'adding_hypotheses' vignette.
#'
#' @param model character, Desired Model (2PL,3PL, GPCM)
#' @param multi logical, multidimensional model if TRUE (available for 2PL)
#'
#' @return list of functions: f (item response function), g (marginal probability of a response pattern), fdot, gdot, and ldot (derivatives with respect to the item parameters)
#' @export
#'
#' @examples
#'
#' funs = load.functions('2PL')
#'
load.functions <- function(model, multi = FALSE) {


    # 2PL
    # ---------------------------------------------------------------------


    # 2PL
    if (model == "2PL" & !multi) {

        f_2pl <- function(th, a, d, x) exp(x * (a *
            th + d))/(1 + exp(a * th + d))
        # f1_2pl, f2_2pl: derivatives w.r.t. a and d, as generated by
        # Deriv::Deriv(f_2pl, "a") / Deriv::Deriv(f_2pl, "d") (Deriv 4.3.6)
        f1_2pl <- function(th, a, d, x) {
            .e2 <- a * th + d
            .e3 <- exp(.e2)
            .e4 <- 1 + .e3
            th * exp(x * .e2) * (x - .e3/.e4)/.e4
        }
        f2_2pl <- function(th, a, d, x) {
            .e2 <- a * th + d
            .e3 <- exp(.e2)
            .e4 <- 1 + .e3
            exp(x * .e2) * (x - .e3/.e4)/.e4
        }

        g <- function(pattern, pars) {
            re <- gauss_hermite(function(th) {
                prod(f_2pl(th, pars$a, pars$d, pattern))
            }, order = 30)
            return(re)
        }
        fdot_2pl <- function(th, a, d, x) {
            res <- f_2pl(th, a, d, x)
            temp1 <- f1_2pl(th, a, d, x)
            temp2 <- f2_2pl(th, a, d, x)

            a <- lapply(seq_len(length(x)), function(i) {
                prod(res[-i]) * c(temp1[i], temp2[i])
            })
            as.numeric(unlist(a))
        }
        gdot <- function(pattern, pars) {
            re <- gauss_hermite(function(th) {
                fdot_2pl(th, pars$a, pars$d, pattern)
            }, order = 30)
            return(re)
        }
        ldot <- function(pattern, pars) {
            re <- gdot(pattern, pars)/g(pattern, pars)
            return(re)
        }

        funlist <- list(f = f_2pl, g = g, fdot = fdot_2pl,
            gdot = gdot, ldot = ldot)

    }


    # 2PL multi
    # ---------------------------------------------------------------


    # 2PL
    if (model == "2PL" & multi) {

        f_2pl_multi <- function(th1, th2, a1, a2, d,
            x) exp(x * (a1 * th1 + a2 * th2 + d))/(1 +
            exp(a1 * th1 + a2 * th2 + d))
        # f1_2pl_multi, f2_2pl_multi, f3_2pl_multi: derivatives w.r.t.
        # a1, a2 and d, as generated by
        # Deriv::Deriv(f_2pl_multi, "a1") etc. (Deriv 4.3.6)
        f1_2pl_multi <- function(th1, th2, a1, a2, d, x) {
            .e3 <- a1 * th1 + a2 * th2 + d
            .e4 <- exp(.e3)
            .e5 <- 1 + .e4
            th1 * exp(x * .e3) * (x - .e4/.e5)/.e5
        }
        f2_2pl_multi <- function(th1, th2, a1, a2, d, x) {
            .e3 <- a1 * th1 + a2 * th2 + d
            .e4 <- exp(.e3)
            .e5 <- 1 + .e4
            th2 * exp(x * .e3) * (x - .e4/.e5)/.e5
        }
        f3_2pl_multi <- function(th1, th2, a1, a2, d, x) {
            .e3 <- a1 * th1 + a2 * th2 + d
            .e4 <- exp(.e3)
            .e5 <- 1 + .e4
            exp(x * .e3) * (x - .e4/.e5)/.e5
        }

        g <- function(pattern, pars) {
            re <- gauss_hermite(function(th1) {
                re <- gauss_hermite(function(th2) {
                  prod(f_2pl_multi(th1, th2, pars$a[,
                    1], pars$a[, 2], pars$d, pattern))
                }, order = 30)
            }, order = 30)
            return(re)
        }
        fdot_2pl_multi <- function(th1, th2, a1, a2,
            d, x) {
            res <- f_2pl_multi(th1, th2, a1, a2, d,
                x)
            temp1 <- f1_2pl_multi(th1, th2, a1, a2, d, x)
            temp2 <- f2_2pl_multi(th1, th2, a1, a2, d, x)
            temp3 <- f3_2pl_multi(th1, th2, a1, a2, d, x)

            a <- lapply(seq_len(length(x)), function(i) {
                prod(res[-i]) * c(temp1[i], temp2[i],
                  temp3[i])
            })
            as.numeric(unlist(a))
        }
        gdot <- function(pattern, pars) {
            re <- gauss_hermite(function(th1) {
                re <- gauss_hermite(function(th2) {
                  fdot_2pl_multi(th1, th2, pars$a[,
                    1], pars$a[, 2], pars$d, pattern)
                }, order = 30)
            }, order = 30)
            return(re)
        }
        ldot <- function(pattern, pars) {
            re <- gdot(pattern, pars)/g(pattern, pars)
            return(re)
        }

        funlist <- list(f = f_2pl_multi, g = g, fdot = fdot_2pl_multi,
            gdot = gdot, ldot = ldot)

    }


    # 3PL
    # ---------------------------------------------------------------------

    # 3PL
    if (model == "3PL" & !multi) {

        f_3pl <- function(th, a, d, g, x) (1 - x) +
            (2 * x - 1) * logitinv(g) + (2 * x - 1) *
            (1 - logitinv(g))/(1 + exp(-(a * th + d)))

        # f1_3pl, f2_3pl, f3_3pl: derivatives w.r.t. a, d and g, as
        # generated by
        # Deriv::Deriv(f_3pl, "a") etc. (Deriv 4.3.6)
        f1_3pl <- function(th, a, d, g, x) {
            .e2 <- exp(-(a * th + d))
            th * (1 - logitinv(g)) * (2 * x - 1) * .e2/(1 + .e2)^2
        }
        f2_3pl <- function(th, a, d, g, x) {
            .e2 <- exp(-(a * th + d))
            (1 - logitinv(g)) * (2 * x - 1) * .e2/(1 + .e2)^2
        }
        f3_3pl <- function(th, a, d, g, x) {
            .e2 <- exp(-g)
            (1 - 1/(1 + exp(-(a * th + d)))) * (2 * x - 1) * .e2/(1 +
                .e2)^2
        }

        g <- function(pattern, pars) {
            re <- gauss_hermite(function(th) {
                prod(f_3pl(th, pars$a, pars$d, pars$g,
                  pattern))
            }, order = 30)
            return(re)
        }
        fdot_3pl <- function(th, a, d, g, x) {
            res <- f_3pl(th, a, d, g, x)
            temp1 <- f1_3pl(th, a, d, g, x)
            temp2 <- f2_3pl(th, a, d, g, x)
            temp3 <- f3_3pl(th, a, d, g, x)

            a <- lapply(seq_len(length(x)), function(i) {
                prod(res[-i]) * c(temp1[i], temp2[i],
                  temp3[i])
            })
            as.numeric(unlist(a))
        }
        gdot <- function(pattern, pars) {
            re <- gauss_hermite(function(th) {
                fdot_3pl(th, pars$a, pars$d, pars$g,
                  pattern)
            }, order = 30)
            return(re)
        }
        ldot <- function(pattern, pars) {
            re <- gdot(pattern, pars)/g(pattern, pars)
            return(re)
        }

        funlist <- list(f = f_3pl, g = g, fdot = fdot_3pl,
            gdot = gdot, ldot = ldot)

    }



    # GPCM
    # --------------------------------------------------------------------


    # GPCM
    if (model == "gpcm") {

        f_gpcm <- function(th, a, d1, d2, x) exp(x *
            ((2 - x) * (a * th + d1) + (x - 1)/2 *
                (2 * a * th + d2)))/(1 + exp(a * th +
            d1) + exp(2 * a * th + d2))
        # f1_gpcm, f2_gpcm, f3_gpcm: derivatives w.r.t. a, d1 and d2, as
        # generated by
        # Deriv::Deriv(f_gpcm, "a") etc. (Deriv 4.3.6)
        f1_gpcm <- function(th, a, d1, d2, x) {
            .e1 <- a * th
            .e3 <- 2 * .e1 + d2
            .e4 <- .e1 + d1
            .e5 <- exp(.e3)
            .e6 <- exp(.e4)
            .e8 <- 1 + .e5 + .e6
            th * exp(x * ((2 - x) * .e4 + .e3 * (x - 1)/2)) * (x - (2 *
                .e5 + .e6)/.e8)/.e8
        }
        f2_gpcm <- function(th, a, d1, d2, x) {
            .e1 <- a * th
            .e2 <- .e1 + d1
            .e4 <- 2 * .e1 + d2
            .e5 <- exp(.e2)
            .e7 <- 1 + exp(.e4) + .e5
            .e8 <- 2 - x
            exp(x * (.e8 * .e2 + .e4 * (x - 1)/2)) * (x * .e8 - .e5/.e7)/.e7
        }
        f3_gpcm <- function(th, a, d1, d2, x) {
            .e1 <- a * th
            .e3 <- 2 * .e1 + d2
            .e4 <- .e1 + d1
            .e5 <- exp(.e3)
            .e7 <- 1 + .e5 + exp(.e4)
            .e8 <- x - 1
            exp(x * ((2 - x) * .e4 + .e3 * .e8/2)) * (x * .e8/2 - .e5/.e7)/.e7
        }

        g <- function(pattern, pars) {
            re <- gauss_hermite(function(th) {
                prod(f_gpcm(th, pars$a, pars$d[, 2],
                  pars$d[, 3], pattern))
            }, order = 50)
            return(re)
        }

        fdot_gpcm <- function(th, a, d1, d2, x) {
            res <- f_gpcm(th, a, d1, d2, x)
            temp1 <- f1_gpcm(th, a, d1, d2, x)
            temp2 <- f2_gpcm(th, a, d1, d2, x)
            temp3 <- f3_gpcm(th, a, d1, d2, x)

            a <- lapply(seq_len(length(x)), function(i) {
                prod(res[-i]) * c(temp1[i], temp2[i],
                  temp3[i])
            })
            as.numeric(unlist(a))
        }

        gdot <- function(pattern, pars) {
            re <- gauss_hermite(function(th) {
                fdot_gpcm(th, pars$a, pars$d[, 2],
                  pars$d[, 3], pattern)
            }, order = 50)
            return(re)
        }
        ldot <- function(pattern, pars) {
            re <- gdot(pattern, pars)/g(pattern, pars)
            return(re)
        }

        funlist <- list(f = f_gpcm, g = g, fdot = fdot_gpcm,
            gdot = gdot, ldot = ldot)
    }


    return(funlist)

}


